from datetime import date
from io import BytesIO
from xml.sax.saxutils import escape

from .role_filter import handover_for_user

FOOTER = ("Generated by CONTINEX. Facts were extracted from the project's documents and each one "
          "was checked against a source quote and approved by a person. Answers marked 'stated' "
          "come from people and are not verified. No passwords are stored in this document.")


def _d(iso):
    try:
        return date.fromisoformat(iso).strftime("%d %b %Y")
    except (TypeError, ValueError):
        return iso or ""


def _entry(key, e):
    meta = []
    if key in ("task", "responsibility"):
        meta.append("Owner: needs a new owner (currently the person leaving)" if e["needs_new_owner"]
                    else f"Owner: {e['owner'] or 'not named in the records'}")
        meta.append(f"Next step: {e.get('next_step') or 'Not found in the records.'}")
        meta.append(f"Already tried: {e.get('tried') or 'Not found in the records.'}")
    elif key == "access_pointer" and e["owner"]:
        meta.append(f"Held by: {e['owner']}")
    when = e["date_text"] or ""
    if e["date"]:
        when = f"{when} ({_d(e['date'])})" if when else _d(e["date"])
    if when:
        meta.append(f"Date: {when}")
    if e["reason"]:
        meta.append(f"{'Reason' if key == 'decision' else 'Why'}: {e['reason']}")
    if key == "claim":
        meta.append("Check this before relying on it.")
    return {"head": e["text"], "meta": meta, "quote": e["quote"], "source": e["source"]}


def build_document(user, handover):
    """Everything comes from handover_for_user, so the file respects the viewer's role."""
    data = handover_for_user(user, handover)
    p = handover.project
    approver = handover.created_by.get_username() if handover.created_by else "a manager"
    sections = {s["key"]: s for s in data["sections"]}
    pairs = [(s["key"], e) for s in data["sections"] for e in s["entries"]]

    n_tasks = len(sections.get("task", {}).get("entries", []))
    n_new = sum(1 for k, e in pairs if e["needs_new_owner"])
    open_gaps = [g for g in data["gaps"] if g["status"] == "open"]
    done_gaps = [g for g in data["gaps"] if g["status"] == "answered"]

    blocks = [{"title": "At a glance", "entries": [], "intro":
               f"{n_tasks} open task(s), {n_new} needing a new owner, {len(data['warnings'])} risk(s) "
               f"to watch and {len(open_gaps)} question(s) still unanswered."}]

    timeline = sorted((e["date"], e["text"]) for k, e in pairs if e["date"])
    if timeline:
        blocks.append({"title": "Timeline", "entries": [],
                       "table": {"head": ["Date", "What"], "rows": [[_d(d), t] for d, t in timeline]}})

    people = {}
    for k, e in pairs:
        if e["owner"] and k in ("task", "responsibility", "access_pointer"):
            people.setdefault(e["owner"], []).append(e["text"])
    if people:
        blocks.append({"title": "People and what they own", "entries": [], "table": {
            "head": ["Person", "Items", "Examples"],
            "rows": [[n, str(len(v)), "; ".join(v[:3])] for n, v in sorted(people.items())]}})

    for key, s in sections.items():
        if s["entries"]:
            intro = "Passwords and keys are not stored here. This points to where access is held." \
                if key == "access_pointer" else ""
            blocks.append({"title": s["title"], "intro": intro,
                           "entries": [_entry(key, e) for e in s["entries"]]})

    if data["warnings"]:
        blocks.append({"title": "Risks to be aware of",
                       "entries": [{"head": w["message"], "meta": [], "quote": "", "source": ""}
                                   for w in data["warnings"]]})
    if done_gaps:
        blocks.append({"title": "Information stated by the leaving person", "entries": [
            {"head": g["question"],
             "meta": [f"Stated by {g['answered_by'] or 'a team member'}: {g['answer']}",
                      "Stated, not verified."],
             "quote": g["quote"], "source": g["source"]} for g in done_gaps]})
    if open_gaps:
        blocks.append({"title": "Unanswered questions", "intro":
                       "The records raise these questions but nobody has answered them yet.",
                       "entries": [{"head": g["question"], "meta": [g["why"]] if g["why"] else [],
                                    "quote": g["quote"], "source": g["source"]} for g in open_gaps]})

    sources = sorted({e["source"] for k, e in pairs} | {g["source"] for g in data["gaps"] if g["source"]})
    if sources:
        blocks.append({"title": "Source files", "entries": [], "intro": ", ".join(sources)})
    if data["hidden_total"]:
        blocks.append({"title": "Access note", "entries": [], "intro":
                       f"{data['hidden_total']} item(s) are not shown because of your access level."})

    return {
        "title": f"Handover: {p.name}",
        "meta": [("Project", p.name), ("Type", p.get_project_type_display()),
                 ("Purpose", p.description or "Not stated"),
                 ("Person leaving", data["leaver"]), ("Last working day", _d(data["leave_date"])),
                 ("Version", str(handover.version)), ("Approved by", approver),
                 ("Approved on", handover.created_at.strftime("%d %b %Y")),
                 ("Prepared for role", data["role"].capitalize())],
        "blocks": blocks,
        "footer": FOOTER,
    }


# ---------- PDF ----------
def _p(text):
    # the built-in PDF font is Latin only; unsupported characters become "?" instead of black boxes
    return escape((text or "").encode("cp1252", "replace").decode("cp1252"))


def render_pdf(doc):
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import KeepTogether, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

    ss = getSampleStyleSheet()
    navy, indigo, grey = colors.HexColor("#111936"), colors.HexColor("#4f46e5"), colors.HexColor("#475569")
    H1 = ParagraphStyle("H1", parent=ss["Title"], alignment=0, fontSize=22, textColor=navy, spaceAfter=8)
    H2 = ParagraphStyle("H2", parent=ss["Heading2"], textColor=indigo, spaceBefore=14, spaceAfter=6)
    B = ParagraphStyle("B", parent=ss["BodyText"], fontSize=10, leading=14)
    SM = ParagraphStyle("SM", parent=B, fontSize=9, textColor=grey)
    Q = ParagraphStyle("Q", parent=SM, leftIndent=10, fontName="Helvetica-Oblique")

    def table(rows, widths, head=False):
        t = Table([[Paragraph(_p(c), B) for c in r] for r in rows], colWidths=widths)
        style = [("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#d9dcf7")),
                 ("VALIGN", (0, 0), (-1, -1), "TOP"),
                 ("BACKGROUND", (0, 0), (0, -1) if not head else (-1, 0), colors.HexColor("#f1efff"))]
        t.setStyle(TableStyle(style))
        return t

    story = [Paragraph(_p(doc["title"]), H1),
             table([[k, v] for k, v in doc["meta"]], [45 * mm, 125 * mm])]
    for b in doc["blocks"]:
        story.append(Paragraph(_p(b["title"]), H2))
        if b.get("intro"):
            story.append(Paragraph(_p(b["intro"]), B))
        if b.get("table"):
            t = b["table"]
            n = len(t["head"])
            widths = [30 * mm, 140 * mm] if n == 2 else [40 * mm, 18 * mm, 112 * mm]
            story.append(table([t["head"]] + t["rows"], widths, head=True))
        for e in b["entries"]:
            parts = [Paragraph(f"<b>{_p(e['head'])}</b>", B)]
            parts += [Paragraph(_p(m), SM) for m in e["meta"]]
            if e["quote"]:
                parts.append(Paragraph(f"&ldquo;{_p(e['quote'])}&rdquo; ({_p(e['source'])})", Q))
            parts.append(Spacer(1, 6))
            story.append(KeepTogether(parts))
    story += [Spacer(1, 14), Paragraph(_p(doc["footer"]), SM)]

    def page_no(canvas, d):
        canvas.setFont("Helvetica", 8)
        canvas.setFillColor(grey)
        canvas.drawRightString(A4[0] - 20 * mm, 10 * mm, f"CONTINEX  |  Page {d.page}")

    buf = BytesIO()
    SimpleDocTemplate(buf, pagesize=A4, leftMargin=20 * mm, rightMargin=20 * mm, topMargin=18 * mm,
                      bottomMargin=18 * mm, title=doc["title"]).build(story, onFirstPage=page_no,
                                                                      onLaterPages=page_no)
    return buf.getvalue()


# ---------- Word ----------
def render_docx(doc):
    from docx import Document
    from docx.shared import Pt

    d = Document()
    d.styles["Normal"].font.name = "Calibri"
    d.styles["Normal"].font.size = Pt(10.5)
    d.add_heading(doc["title"], 0)
    t = d.add_table(rows=0, cols=2)
    t.style = "Table Grid"
    for k, v in doc["meta"]:
        row = t.add_row().cells
        row[0].text, row[1].text = k, v
        row[0].paragraphs[0].runs[0].bold = True
    for b in doc["blocks"]:
        d.add_heading(b["title"], 1)
        if b.get("intro"):
            d.add_paragraph(b["intro"])
        if b.get("table"):
            tb = d.add_table(rows=1, cols=len(b["table"]["head"]))
            tb.style = "Table Grid"
            for i, h in enumerate(b["table"]["head"]):
                tb.rows[0].cells[i].text = h
                tb.rows[0].cells[i].paragraphs[0].runs[0].bold = True
            for r in b["table"]["rows"]:
                cells = tb.add_row().cells
                for i, c in enumerate(r):
                    cells[i].text = c
        for e in b["entries"]:
            d.add_paragraph().add_run(e["head"]).bold = True
            for m in e["meta"]:
                d.add_paragraph(m, style="List Bullet")
            if e["quote"]:
                q = d.add_paragraph()
                q.add_run(f"\u201c{e['quote']}\u201d ({e['source']})").italic = True
    d.add_paragraph()
    d.add_paragraph(doc["footer"]).runs[0].italic = True
    buf = BytesIO()
    d.save(buf)
    return buf.getvalue()